// Табло часов через подмену времени (найдено вживую 2026-10-17): часы рисуют «часы» и «минуты» сами,
// каждое значение 0..99 → две цифры, 100+ → пара гаснет. Обновляется сразу по уведомлению iAP
// (03 09 … 09), проверено до 20 раз/с. Букв у табло нет — только цифры и похожие на них знаки.
#pragma once
#include <cstdint>
#include <string>

namespace wul {

constexpr uint8_t kBlankPair = 100;            // значение, при котором пара цифр гаснет

struct DisplayPair { uint8_t h = 0, m = 0; };   // что отдать часам вместо времени

// Текст из 4 знаков → пары. Допустимо: 0-9, похожие буквы (O o D→0, I i l→1, Z z→2, S s→5,
// b G→6, B→8, g q→9), пробел/«_». Пробел гасит всю пару (часы не умеют гасить одну цифру),
// поэтому « 1» и «1 » в паре — ошибка. Возвращает false и текст ошибки, если строку не показать.
bool textToPairs(const std::string& text, DisplayPair& out, std::string* error = nullptr);

// Эквалайзер: уровень 0..5 → цифра с бо́льшим числом горящих сегментов (1,7,4,3,9,8).
uint8_t eqGlyph(uint8_t level);
DisplayPair eqPairs(const uint8_t levels[4]);   // 4 полосы → пары

}  // namespace wul
