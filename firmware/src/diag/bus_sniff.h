// Прослушка второй последовательной шины межплатного разъёма (верхний вывод 5, «85 00 2C…»):
// только приём на GPIO34, сами ничего не передаём. Скорость определяется по самому короткому
// импульсу на линии; кадры режутся по паузе > 3 мс. Нужна, чтобы понять, что по ней идёт —
// табло (тогда буквы и полоски на табло) или контроллер лампы (тогда раздельные цвета).
#pragma once
#include <cstdint>
#include <string>

namespace sniff {

void begin(int pin);                    // запустить измерение скорости и приём
void loop();
uint32_t baud();                        // 0 — ещё не определена / нет сигнала
void setBaud(uint32_t b);               // задать вручную (8N1)
void redetect();                        // измерить скорость заново
std::string json(uint32_t sinceMs);     // {"baud":…,"edges":…,"frames":[{"ms":…,"hex":"…"}]}
// Сырые фронты: запись времени каждого фронта (мкс) на ms миллисекунд — чтобы точно измерить скорость
// и форму сигнала вне UART. На время записи приём байтов останавливается.
void captureEdges(uint32_t ms);
std::string edgesJson();                // {"level0":…,"t":[мкс от первого фронта…]}

}  // namespace sniff
